#!/usr/bin/env node
/**
 * generate-puzzle.mjs
 *
 * Calls Claude to generate a 3-round Fibbed puzzle on a given topic,
 * then inserts it as a pending draft into Supabase (service-role, bypasses RLS).
 *
 * Usage:
 *   node scripts/generate-puzzle.mjs "South African Elections"
 *   node scripts/generate-puzzle.mjs   # picks a topic automatically
 *
 * Required env vars:
 *   ANTHROPIC_API_KEY
 *   SUPABASE_URL          (same as VITE_SUPABASE_URL)
 *   SUPABASE_SERVICE_ROLE_KEY
 */

import Anthropic from '@anthropic-ai/sdk'
import { createClient } from '@supabase/supabase-js'

const SYSTEM = `\
You are a fact-checker and puzzle writer for Fibbed, a daily newspaper-style game.
Each day's puzzle has three rounds. You write one puzzle at a time.

A puzzle is a JSON array of exactly three round objects:
[
  { round 1: easy },
  { round 2: medium },
  { round 3: hard }
]

Each round object has this exact shape:
{
  "theme": "<short topic label, 2–5 words>",
  "level": "easy" | "medium" | "hard",
  "truths": [
    { "text": "<statement>", "source_url": "<URL>", "source_label": "<site: page title>" },
    { "text": "<statement>", "source_url": "<URL>", "source_label": "<site: page title>" },
    { "text": "<statement>", "source_url": "<URL>", "source_label": "<site: page title>" }
  ],
  "fib": {
    "text": "<plausible false statement>",
    "explanation": "<why it is false, in one sentence>",
    "source_url": "<URL>",
    "source_label": "<site: page title>"
  }
}

Rules:
- All three truths must be verifiably true, with real source URLs.
- The fib must sound plausible — a confident player should be unsure.
- The fib cannot be obviously absurd; it must be in the same register as the truths.
- The explanation must correct the fib clearly and briefly.
- Rounds escalate in obscurity: easy truths are well-known, hard truths are niche facts.
- Return ONLY valid JSON — no markdown, no commentary, no code fences.`

const USER = (topic) =>
  `Write a three-round Fibbed puzzle about: ${topic}

Return only the JSON array. No extra text.`

async function generate(topic) {
  const client = new Anthropic()
  const msg = await client.messages.create({
    model: 'claude-opus-5-5',
    max_tokens: 2048,
    messages: [{ role: 'user', content: USER(topic) }],
    system: SYSTEM,
  })
  const text = msg.content.find((b) => b.type === 'text')?.text ?? ''
  return JSON.parse(text)
}

function validate(rounds) {
  if (!Array.isArray(rounds) || rounds.length !== 3) throw new Error('Expected 3 rounds')
  for (const r of rounds) {
    if (!r.theme || !r.level || !['easy', 'medium', 'hard'].includes(r.level))
      throw new Error(`Invalid level: ${r.level}`)
    if (!Array.isArray(r.truths) || r.truths.length !== 3)
      throw new Error(`Round "${r.theme}" needs exactly 3 truths`)
    for (const t of r.truths) {
      if (!t.text || !t.source_url || !t.source_label) throw new Error('Truth missing fields')
    }
    if (!r.fib?.text || !r.fib?.explanation || !r.fib?.source_url || !r.fib?.source_label)
      throw new Error(`Round "${r.theme}" fib missing fields`)
  }
}

async function insert(rounds, notes) {
  const url = process.env.SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set')
  const db = createClient(url, key, { auth: { persistSession: false } })
  const { data, error } = await db
    .from('puzzle_drafts')
    .insert({ rounds: JSON.stringify(rounds), notes: notes ?? null })
    .select('id')
    .single()
  if (error) throw new Error(`Supabase insert failed: ${error.message}`)
  return data.id
}

const topic = process.argv[2] ?? 'a surprising fact from science, history or nature'

console.log(`Generating puzzle on: ${topic}`)

const rounds = await generate(topic)
validate(rounds)
console.log('Generated:', rounds.map((r) => `${r.theme} (${r.level})`).join(', '))

const id = await insert(rounds, `Generated by Claude on ${new Date().toISOString().slice(0, 10)}`)
console.log(`Inserted draft: ${id}`)
